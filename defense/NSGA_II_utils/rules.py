import math
from math import gcd
import numpy as np
from scipy.spatial import ConvexHull, QhullError

import defense.NSGA_II_utils.config as config
import defense.NSGA_II_utils.field as field

# rules.py defines the fitness functions that our algorithm optimizes for

# defining all possible fitness scores based on count of dummy electrodes (in a timestep)
# 1 - 1/sqrt(n): n=1 -> 0.0 (best), rises with n, n=0 -> 1.0 (worst) where lower is better. 
_COUNT_FITNESS = {0: 1.0}
for _ in range(1, config.MAX_DUMMIES_PER_STEP+1):
    _COUNT_FITNESS |= {_: 1 - 1/(math.sqrt(_))}


def count_score(schedule):
    """
    Mean of _COUNT_FITNESS over every timestep: min 0 (best), max 1 (worst).
    """
    per_step = [_COUNT_FITNESS[len(dummies)] for dummies in schedule]
    return float(np.mean(per_step)) if per_step else 1.0


def _wasted_points(cells):
    """
    Electrode positions enclosed by dummy electrode actuations (Pick's Theorem: Lattice polygon). 
    I (interior lattice points) = Area - B/2 + 1, where B is boundary lattice points. 
    Exception: 2 dummy electrodes can't enclose area, these are scoreed as the area of the square built on their manhattan separation.
    """

    # 2 dummy actuation case 
    if len(cells) == 2:
        (r1, c1), (r2, c2) = cells
        return float((abs(r1 - r2) + abs(c1 - c2)) ** 2)

    pts = np.array(cells, dtype=float)

    try:
        hull = ConvexHull(pts)
    except QhullError:
        direction = pts[1] - pts[0]
        proj = pts @ direction
        lo, hi = pts[np.argmin(proj)], pts[np.argmax(proj)]
        dr, dc = abs(hi[0] - lo[0]), abs(hi[1] - lo[1])
        boundary = gcd(int(round(dr)), int(round(dc))) + 1
        return float(boundary - len(cells))

    verts = pts[hull.vertices]
    area = 0.0
    boundary = 0
    for i in range(len(verts)):
        x1, y1 = verts[i]
        x2, y2 = verts[(i + 1) % len(verts)]
        area += x1 * y2 - x2 * y1
        boundary += gcd(int(round(abs(x2 - x1))), int(round(abs(y2 - y1))))
    area = abs(area) / 2.0
    interior = area - boundary / 2.0 + 1.0

    return (interior + boundary) - len(cells)


def spread_score(schedule):
    """
    mean spread over every timestep: 1 (worse spread, and score given to 1 or 0 dummy actuations), 0 is the best score
    """
    per_step = []
    for dummies in schedule:
        if len(dummies) < 2:
            per_step.append(1.0)
            continue
        wasted = _wasted_points(dummies)
        per_step.append((max(0.0, min(1.0, wasted / len(config.ELECTRODES)))))

    return float(np.mean(per_step)) if per_step else 0.0


_ELECTRODE_SET = set(config.ELECTRODES)


def capture_zone_score(schedule):
    """
    Alternative to prior spread_score. Per timestep: the union of the 3x3 blocks (4 orthogonal + 4 diagonal neighbours + the cell itself) around every dummy actuation,
    intersected with electrode positions, divided by the electrode count. Average is taken over all timesteps. 
    Example:
        if dummy actuation has 9 surrounding electrodes, and only 25 electrodes exist, then 9/25 electrodes cannot be used, which means routing-area cost 
        at that timestep is 9/25 or 0.36. Values scale with size of grid and max_dummies, if on 18x18 grid, then values much smaller. 
    """
    n_elec = len(config.ELECTRODES)
    if n_elec == 0:
        return 0.0

    per_step = []
    for dummies in schedule:
        blocked = set()
        for r, c in dummies:
            for dr in (-1, 0, 1):
                for dc in (-1, 0, 1):
                    if (r + dr, c + dc) in _ELECTRODE_SET:
                        blocked.add((r + dr, c + dc))
        per_step.append(len(blocked) / n_elec)

    return float(np.mean(per_step)) if per_step else 0.0


def _plausibility_scores(prev_cells, cells, elapsed):
    """
    checks how realistically dummy electrodes are moving from one time step to the next.
    - for real DMFBs, droplet's move only one grid step per turn (no diagonals)
    - function penalizes movements that don't match real droplet dynamics 
    """
    scores = []
    for cell in cells:
        dist = min(abs(cell[0] - p[0]) + abs(cell[1] - p[1]) for p in prev_cells)
        if dist <= elapsed:
            scores.append(1.0)
        else:
            scores.append(float(np.exp(-(dist - elapsed) / config.KINEMATIC_SCALE)))
    return scores


def _emf_accuracy(true_cell, dummies):
    """
    finds maximum EMF generated by the real droplet (1) and maximum brightness generated by all dummies combined.
    - return: fraction of the total brightness belongs strictly to the real droplet
    - 0: dummies EMF dominates grid, good defense 
    - 1: real droplet's EMF completely dominates the grid, bad defense
    """
    real_peak = float(field.real_field(true_cell).max())
    dummy_peak = float(field.dummy_sum(dummies).max())
    total = real_peak + dummy_peak
    if total <= 0:
        return 1.0
    p_real = real_peak / total
    return abs(p_real - 0.5) * 2.0


def surrogate_attack_accuracy(schedule, protocol):
    """
    The goal of any defense is to always mitigate the efficiacy of the attacker's model. 
    However, running inference on attacker accuracy is:
         1) computationally expensive 
         2) unrealisitic as real defenses do not have access to knowledge on how an attack is done.
    This function should thus be adjusted based on a surrogate model of the attacker, i.e a belief on how you think the attacker works 
     Currently, we assume the attacker works by maximizing EMF information gain.
    - therefore, this function should return a high score when your surrogate model performs poorly (good obfuscation) and low score when performing well (bad obfuscation). 
    - we clamp this score between [0, 1], where accuracy of 0 is preferred (minimization)
    """
    per_step = []
    prev_cells = None
    elapsed = 0

    # for a very simple model, we assume a surrogate attack model accuracy is proportional to noise and movement pattern created by dummy actuations 
    # high noise and good pattern = low accuracy, opposite = high accuracy. 
    # like before, we minimize 
    for true_cell, dummies in zip(protocol, schedule):
        elapsed += 1
        if not dummies:
            continue

        emf_accuracy = _emf_accuracy(true_cell, dummies)

        if prev_cells:
            plausibility = float(np.mean(_plausibility_scores(prev_cells, dummies, elapsed)))
        else:
            plausibility = 0.0  # no track record yet to judge it against

        kinematic_accuracy = 1.0 - plausibility

        # the attacker only needs one working heuristic to win, so a bad score on either axis should pull accuracy back up, not
        # get masked by the other axis being good. 
        per_step.append(1.0 - (1.0 - emf_accuracy) * (1.0 - kinematic_accuracy))

        prev_cells = dummies
        elapsed = 0

    return float(np.mean(per_step)) if per_step else 1.0
